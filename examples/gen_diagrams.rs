/// Why an archive reads correctly while someone else is still writing it.
fn read_path() -> String {
    claim(
        DB_RS,
        "const LIVE_WAL_PREDICATE",
        "the watermark is one shared predicate",
    );
    claim(
        DB_RS,
        "ts > COALESCE(",
        "the watermark is a `ts >` comparison",
    );
    claim(
        READ_RS,
        "encoder.encode(stream, &db.live_wal(",
        "the tail is materialized through the encoder",
    );
    claim(
        READ_RS,
        "segments.push(tail.bytes)",
        "the tail is appended as the newest segment",
    );
    claim(
        READ_RS,
        "pub fn read_archive",
        "the entry point is `read_archive`",
    );

    let mut s = header("dendro: the read path", "LR");
    s.push_str("  nodesep=0.4;\n  ranksep=0.75;\n");

    s.push_str(&history("sealed", "seq 0|seq 1|seq 2", dat::DURABLE));
    s.push_str(&history("live", "row|row", dat::DERIVED));
    s.push_str(&compute(
        "watermark",
        "1. select live rows\\n`ts > MAX(last_ts)`\\nfor this stream, this source",
        op::DECIDE,
    ));
    s.push_str(&compute(
        "materialize",
        "2. materialize the tail\\n`SegmentEncoder`",
        op::OUTPUT,
    ));
    s.push_str(&data(
        "tail",
        "tail\\nparquet bytes, in memory -\\nnever written to the archive",
        dat::DERIVED,
        false,
    ));
    s.push_str(&compute(
        "splice",
        "3. splice\\noldest first, tail last",
        op::TRANSFORM,
    ));
    s.push_str(&data(
        "bytes",
        "parquet bytes\\nopen with any reader",
        dat::CONCEPT,
        false,
    ));

    s.push_str(&format!(
        "  live -> watermark [color=\"{EDGE_UNSEALED}\"];\n  \
           sealed -> watermark [style=dotted, label=\"MAX(last_ts)\"];\n  \
           watermark -> materialize [color=\"{EDGE_UNSEALED}\", \
             label=\"rows past\\lthe watermark\\l\"];\n  \
           materialize -> tail [color=\"{EDGE_UNSEALED}\"];\n  \
           sealed -> splice [color=\"{EDGE_SEALED}\", penwidth=2];\n  \
           tail -> splice [color=\"{EDGE_UNSEALED}\", penwidth=2];\n  \
           splice -> bytes [penwidth=2];\n"
    ));
    s.push_str(&format!(
        "  subgraph cluster_yours {{\n    label=\"yours\";\n    fontsize=14;\n    labeljust=l;\n    \
           style=dashed;\n    color=\"{PANEL_BORDER}\";\n    materialize;\n  }}\n"
    ));

    s.push_str(&key_paths());
    s.push_str("}\n");
    s
}

/// The key for the path charts.
///
/// `rank=same` is what stacks it: these charts are `rankdir=LR`, where an
/// invisible chain would lay the key out horizontally across the full width and
/// it would read as a second diagram rather than a legend.
fn key_paths() -> String {
    let mut s = format!(
        "  subgraph cluster_key {{\n    label=\"key\";\n    fontsize=13;\n    labeljust=l;\n    \
           style=filled;\n    fillcolor=\"{PANEL_FILL}\";\n    color=\"{PANEL_BORDER}\";\n    \
           node [fontsize=11, height=0.3];\n    rank=same;\n"
    );
    // Emitted in reverse: `rank=same` lays a cluster out bottom-to-top in an
    // LR graph, so this is what puts the shape channel at the top, where a
    // reader looking up a mark starts.
    //
    // The two edge colors are shown as a border rather than as a sample edge.
    // A real edge between two points inside a `rank=same` cluster renders
    // VERTICALLY in an LR graph, which reads as a different channel from the
    // horizontal edges it is supposed to explain. A border is still the color
    // itself rather than its name, which is the property that matters.
    s.push_str(&format!(
        "    k_sealed [shape=box, style=filled, fillcolor=\"{PANEL_FILL}\", \
           color=\"{EDGE_SEALED}\", penwidth=3, label=\"sealed\"];\n    \
             k_unsealed [shape=box, style=filled, fillcolor=\"{PANEL_FILL}\", \
           color=\"{EDGE_UNSEALED}\", penwidth=3, label=\"unsealed\"];\n"
    ));
    s.push_str(&format!(
        "    k_ext [shape=box, style=\"filled,dashed\", fillcolor=\"{}\", \
           label=\"dashed: outside dendro\"];\n",
        dat::EXTERNAL
    ));
    s.push_str(&format!(
        "    k_hist [shape=record, style=filled, fillcolor=\"{}\", \
           label=\"segmented: a history\"];\n",
        dat::DERIVED
    ));
    s.push_str(&format!(
        "    k_dat [shape=box, style=filled, fillcolor=\"{}\", \
           label=\"square: holds\"];\n",
        dat::DURABLE
    ));
    s.push_str(&format!(
        "    k_op [shape=box, style=\"rounded,filled\", fillcolor=\"{}\", \
           label=\"rounded: runs\"];\n",
        op::TRANSFORM
    ));
    s.push_str("  }\n");
    s
}

// ---------------------------------------------------------------------------

fn main() {
    let out = Path::new(env!("CARGO_MANIFEST_DIR")).join("docs");
    std::fs::create_dir_all(&out).expect("create docs/");
    let cat = catalog();

    let charts: [(&str, String); 3] = [
        ("model.dot", model(&cat)),
        ("write-path.dot", write_path(&cat)),
        ("read-path.dot", read_path()),
    ];
    for (name, body) in charts {
        std::fs::write(out.join(name), &body).unwrap_or_else(|e| panic!("write {name}: {e}"));
        println!("wrote docs/{name} ({} bytes)", body.len());
    }
}
