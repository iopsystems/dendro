/// What nests, and what is only a shared key.
///
/// The claim a reader most often gets wrong is that a **stream is not a row in
/// the catalog**. It has no table: it is a name that rows in `segments` and
/// `wal` carry, and the reader is what gathers them. Outline style is spent on
/// exactly that distinction.
fn model(cat: &BTreeMap<String, Vec<String>>) -> String {
    classify_tables(cat);

    // The chart draws these columns; if they are renamed it has to change.
    for (table, col) in [
        ("sources", "labels"),
        ("sources", "clock_anchor_wall_ns"),
        ("segments", "stream"),
        ("segments", "seq"),
        ("segments", "bytes"),
        ("wal", "stream"),
        ("wal", "ts"),
        ("wal", "row"),
    ] {
        assert!(
            cat[table].iter().any(|c| c == col),
            "the model chart draws `{table}.{col}`, which the schema no longer has"
        );
    }

    let mut s = header("dendro: the model", "TB");
    s.push_str("  compound=true;\n  nodesep=0.45;\n  ranksep=0.6;\n");

    // -- the archive IS the cluster. Drawing it as a node beside its own
    //    contents would put the file at the same level as the things inside it.
    s.push_str(&format!(
        "  subgraph cluster_archive {{\n    \
           label=\"archive - one file\";\n    fontsize=16;\n    labeljust=l;\n    \
           style=filled;\n    fillcolor=\"#FAFAFA\";\n    color=\"{PANEL_BORDER}\";\n"
    ));
    s.push_str(&data(
        "source",
        "source\\none producer, one clock domain,\\none label set",
        dat::EXTERNAL,
        false,
    ));
    // Unfilled, and that is the claim: nothing stores a stream. Absence has to
    // be legible, or the reader reads it as merely unmarked.
    s.push_str(
        "    stream [shape=box, style=solid, fillcolor=white, \
           label=\"stream\\na named sequence of rows\\n(no table of its own)\"];\n",
    );
    s.push_str(&history(
        "segments",
        "segment|segment|segment|...",
        dat::DURABLE,
    ));
    s.push_str(&data(
        "row",
        "row\\ntimestamp + opaque bytes",
        dat::DERIVED,
        false,
    ));
    s.push_str(
        "    source -> stream [label=\"names\"];\n    \
             stream -> segments [label=\"is, end to end\"];\n    \
             segments -> row [label=\"holds\"];\n  }\n",
    );

    // -- how it is actually stored ------------------------------------------
    s.push_str(&format!(
        "  subgraph cluster_catalog {{\n    \
           label=\"the catalog (SQLite), inside that same file\";\n    fontsize=16;\n    labeljust=l;\n    \
           style=filled;\n    fillcolor=\"{PANEL_FILL}\";\n    color=\"{PANEL_BORDER}\";\n"
    ));
    s.push_str(&format!(
        "    t_sources [shape=box, style=filled, fillcolor=\"{}\", \
           fontname=\"{MONO}\", label=\"sources\\lid, labels, metadata,\\lcomplete, clock_anchor_wall_ns\\l\"];\n",
        dat::EXTERNAL
    ));
    s.push_str(&format!(
        "    t_segments [shape=box, style=filled, fillcolor=\"{}\", \
           fontname=\"{MONO}\", label=\"segments\\lsource_id, stream, seq,\\lrows, first_ts, last_ts, bytes\\l\"];\n",
        dat::DURABLE
    ));
    s.push_str(&format!(
        "    t_wal [shape=box, style=filled, fillcolor=\"{}\", \
           fontname=\"{MONO}\", label=\"wal\\lsource_id, stream, ts,\\lwall_offset, row\\l\"];\n",
        dat::DERIVED
    ));
    s.push_str("  }\n");

    s.push_str(&format!(
        "  source -> t_sources [style=dotted, label=\"one row\", color=\"{EDGE}\"];\n  \
           segments -> t_segments [style=dotted, color=\"{EDGE_SEALED}\", \
             label=\"one row each,\\lparquet in `bytes`\\l\"];\n  \
           row -> t_wal [style=dotted, color=\"{EDGE_UNSEALED}\", \
             label=\"one row each,\\luntil it is sealed\\l\"];\n"
    ));
    s.push_str(&format!(
        "  stream -> t_segments [style=dotted, color=\"{EDGE}\", \
           label=\"just a column -\\lin `segments` and in `wal`,\\lgathered on read\\l\"];\n"
    ));

    s.push_str(&key_model());
    s.push_str("}\n");
    s
}

/// The key for the model chart.
///
/// `rank=same` lays this out as one horizontal band in a `rankdir=TB` graph.
/// Chained on invisible edges it spreads over the main graph's ranks instead,
/// which are tall, and the gaps between entries read as meaningful.
///
/// The dotted channel is shown as a border for the same reason the path charts
/// show their edge colors that way: a sample edge inside a `rank=same` cluster
/// renders along the wrong axis.
fn key_model() -> String {
    let mut s = format!(
        "  subgraph cluster_key {{\n    label=\"key\";\n    fontsize=13;\n    labeljust=l;\n    \
           style=filled;\n    fillcolor=\"{PANEL_FILL}\";\n    color=\"{PANEL_BORDER}\";\n    \
           node [fontsize=11, height=0.32];\n    rank=same;\n"
    );
    s.push_str(
        "    k_none [shape=box, style=solid, fillcolor=white, \
           label=\"unfilled: nothing\\lstores it\\l\"];\n",
    );
    s.push_str(&format!(
        "    k_fill [shape=box, style=filled, fillcolor=\"{}\", \
           label=\"filled: the tint names\\lthe table that stores it\\l\"];\n",
        dat::DURABLE
    ));
    s.push_str(&format!(
        "    k_hist [shape=record, style=filled, fillcolor=\"{}\", \
           label=\"segmented: a history\"];\n",
        dat::DURABLE
    ));
    s.push_str(&format!(
        "    k_map [shape=box, style=\"filled,dotted\", fillcolor=\"{PANEL_FILL}\", \
           penwidth=2, label=\"dotted: stored as\"];\n"
    ));
    s.push_str("  }\n");
    s
}

