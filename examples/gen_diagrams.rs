/// One row, from the caller's append to a sealed segment.
fn write_path(cat: &BTreeMap<String, Vec<String>>) -> String {
    claim(
        WRITER_RS,
        "Wal { ticks",
        "the writer takes appends as a `Wal` message",
    );
    claim(
        WRITER_RS,
        "Seal { source_id",
        "the writer takes seals as a `Seal` message",
    );
    claim(
        WRITER_RS,
        "sync_channel(1)",
        "the hand-off channel is bounded at 1",
    );
    claim(
        WRITER_RS,
        ".encode(&stream, &rows)",
        "sealing calls the caller's encoder",
    );
    claim(
        WRITER_RS,
        "db.prune_wal(",
        "sealing prunes the WAL it just sealed",
    );
    claim(SEGMENT_RS, "trait SegmentEncoder", "the encoder is a trait");
    assert!(
        cat.contains_key("wal"),
        "the write path draws the `wal` table"
    );

    let mut s = header("dendro: the write path", "LR");
    s.push_str("  nodesep=0.4;\n  ranksep=0.75;\n");

    s.push_str(&data("caller", "caller", dat::EXTERNAL, true));
    s.push_str(&compute(
        "append",
        "1. append\\n`SourceWriter::wal`",
        op::INGEST,
    ));
    // One cell: the channel is bounded at 1, so there is no history to segment.
    // A two-celled glyph here would promise a depth the hand-off does not have.
    s.push_str(&cell("chan", "hand-off\\ncapacity 1", dat::DERIVED));
    s.push_str(&compute(
        "commit",
        "2. commit\\none transaction,\\none fsync",
        op::TRANSFORM,
    ));
    s.push_str(&history("wal", "row|row|row|...", dat::DERIVED));
    s.push_str(&compute(
        "due",
        "3. is this segment due?\\n`seal::SealPolicy`",
        op::DECIDE,
    ));
    s.push_str(&compute(
        "encode",
        "4. encode\\n`SegmentEncoder`",
        op::OUTPUT,
    ));
    s.push_str(&data(
        "segment",
        "segment\\nparquet bytes",
        dat::DURABLE,
        false,
    ));
    s.push_str(&compute(
        "prune",
        "5. prune\\nup to the sealed `last_ts`",
        op::TRANSFORM,
    ));

    s.push_str(&format!(
        "  caller -> append [style=dashed];\n  \
           append -> chan [label=\"rows\"];\n  \
           chan -> commit [label=\"blocks while the\\lwriter is busy\\l\"];\n  \
           commit -> wal [color=\"{EDGE_UNSEALED}\", penwidth=2, \
             label=\"durable, and\\lreadable now\\l\"];\n  \
           wal -> due [style=dotted, label=\"rows, bytes, age\"];\n  \
           due -> encode [label=\"yes\"];\n  \
           wal -> encode [color=\"{EDGE_UNSEALED}\", label=\"this stream's\\llive rows\\l\"];\n  \
           encode -> segment [color=\"{EDGE_SEALED}\", penwidth=2];\n  \
           segment -> prune [style=dotted];\n  \
           prune -> wal [style=dashed, constraint=false, \
             label=\"only this stream,\\lonly up to `last_ts`\\l\"];\n"
    ));

    // The boundary is the whole point of the chart, so draw it.
    s.push_str(&format!(
        "  subgraph cluster_yours {{\n    label=\"yours\";\n    fontsize=14;\n    labeljust=l;\n    \
           style=dashed;\n    color=\"{PANEL_BORDER}\";\n    encode;\n  }}\n"
    ));

    s.push_str(&key_paths());
    s.push_str("}\n");
    s
}

