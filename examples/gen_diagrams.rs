/// The `SCHEMA_SQL` literal, lifted out of `db.rs`.
fn schema_sql() -> &'static str {
    let anchor = "const SCHEMA_SQL: &str = \"";
    let start = DB_RS
        .find(anchor)
        .expect("db.rs no longer defines SCHEMA_SQL - the diagrams describe a schema that is gone")
        + anchor.len();
    let rest = &DB_RS[start..];
    let end = rest
        .find("\";")
        .expect("SCHEMA_SQL literal is unterminated");
    &rest[..end]
}

/// Catalog tables and their columns, parsed from the schema.
fn catalog() -> BTreeMap<String, Vec<String>> {
    let mut out = BTreeMap::new();
    for chunk in schema_sql().split("CREATE TABLE ").skip(1) {
        let (name, rest) = chunk.split_once('(').expect("CREATE TABLE without a body");
        let body = &rest[..rest.find(");").expect("unterminated CREATE TABLE")];
        let cols = body
            .lines()
            .filter_map(|l| {
                let l = l.trim();
                if l.is_empty() || l.starts_with("--") || l.starts_with("PRIMARY KEY") {
                    return None;
                }
                l.split_whitespace().next().map(str::to_string)
            })
            .collect();
        out.insert(name.trim().to_string(), cols);
    }
    out
}

/// Abort unless `haystack` contains `needle`, naming the claim that broke.
fn claim(haystack: &str, needle: &str, what: &str) {
    assert!(
        haystack.contains(needle),
        "the diagrams claim {what}, but `{needle}` is no longer in the source.\n\
         Fix the diagram or the claim - do not delete this assertion."
    );
}

/// Abort on a table the diagrams neither draw nor deliberately omit.
///
/// The same rule `every_schema_table_is_either_copied_or_deliberately_dropped`
/// applies to the rewrite path: silence is the failure mode worth preventing,
/// because a chart missing a table still renders as a complete-looking chart.
fn classify_tables(cat: &BTreeMap<String, Vec<String>>) {
    /// Drawn in the storage column of the model chart.
    const DRAWN: &[&str] = &["sources", "segments", "wal"];
    /// Real, and deliberately not drawn, with the reason.
    const NOT_DRAWN: &[(&str, &str)] = &[
        (
            "clock_offsets",
            "a per-source observation series; it carries no part of the \
             archive -> stream -> segment -> row model the chart is about",
        ),
        (
            "schema_version",
            "one row, written at creation; describes the catalog rather than \
             appearing in it",
        ),
    ];

    for name in cat.keys() {
        let drawn = DRAWN.contains(&name.as_str());
        let omitted = NOT_DRAWN.iter().any(|(t, _)| t == name);
        assert!(
            drawn ^ omitted,
            "catalog table `{name}` is neither drawn nor deliberately omitted \
             (or is listed as both). Add it to DRAWN, or to NOT_DRAWN with the \
             reason it does not belong in the model chart."
        );
    }
    for t in DRAWN.iter().chain(NOT_DRAWN.iter().map(|(t, _)| t)) {
        assert!(
            cat.contains_key(*t),
            "the diagrams classify a table `{t}` the schema no longer has"
        );
    }
}

