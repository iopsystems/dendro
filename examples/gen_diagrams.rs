//! Generate dendro's conceptual diagrams.
//!
//! Run with `docs/regen.sh`, which renders the emitted `.dot` files to SVG.
//! CI fails on any diff against the committed output, so a rename the diagrams
//! claim will either show up renamed or break this program.
//!
//! **Derived, not drawn.** Every node and edge here is checked against the
//! crate's real structures at generation time: the catalog comes from
//! `SCHEMA_SQL` in `db.rs`, the writer's message kinds from its `Msg` enum, the
//! read path's watermark from `LIVE_WAL_PREDICATE`. A claim that stops being
//! true of the source aborts the run rather than rendering a stale picture.

use std::collections::BTreeMap;
use std::path::Path;

const DB_RS: &str = include_str!("../src/db.rs");
const WRITER_RS: &str = include_str!("../src/writer.rs");
const READ_RS: &str = include_str!("../src/read.rs");
const SEGMENT_RS: &str = include_str!("../src/segment.rs");

// ---------------------------------------------------------------------------
// The visual language, shared by every chart in the set.
// ---------------------------------------------------------------------------

/// Operation fills — ColorBrewer Accent, pastel because these are large filled
/// areas a reader looks at for a long time.
mod op {
    pub const INGEST: &str = "#BEAED4";
    pub const TRANSFORM: &str = "#7FC97F";
    pub const DECIDE: &str = "#FFFF99";
    pub const OUTPUT: &str = "#FDC086";
}

/// Data tints — lighter than the operation fills, so data reads as quieter
/// than compute.
mod dat {
    pub const EXTERNAL: &str = "#E6DEF2";
    pub const DERIVED: &str = "#EDEDED";
    pub const DURABLE: &str = "#FBE3CB";
    pub const CONCEPT: &str = "#DDE4CF";
}

const EDGE: &str = "#4D4D4D";
/// The two paths worth separating, in Okabe-Ito colors: rows that are durable
/// but not yet sealed, and rows that have been sealed.
const EDGE_UNSEALED: &str = "#CC79A7";
const EDGE_SEALED: &str = "#D55E00";
const PANEL_FILL: &str = "#F2F2F2";
const PANEL_BORDER: &str = "#9E9E9E";

const FONT: &str = "Helvetica";
const MONO: &str = "Courier";

fn header(title: &str, rankdir: &str) -> String {
    format!(
        "// GENERATED by `cargo run --example gen_diagrams` - do not edit.\n\
         // Source of truth: src/db.rs, src/writer.rs, src/read.rs, src/segment.rs.\n\
         digraph {{\n  \
           label=\"{title}\";\n  \
           labelloc=t;\n  \
           fontname=\"{FONT}\";\n  \
           fontsize=20;\n  \
           rankdir={rankdir};\n  \
           bgcolor=white;\n  \
           node [fontname=\"{FONT}\", fontsize=14, penwidth=1.4, color=\"{EDGE}\"];\n  \
           edge [fontname=\"{FONT}\", fontsize=13, color=\"{EDGE}\", penwidth=1.4];\n"
    )
}

/// A thing that runs. Rounded, always.
fn compute(id: &str, label: &str, fill: &str) -> String {
    format!(
        "  {id} [shape=box, style=\"rounded,filled\", fillcolor=\"{fill}\", label=\"{label}\"];\n"
    )
}

/// A thing that holds. Square, always.
///
/// `dashed` means ONE thing across the whole set: outside dendro. It is not
/// spent on "in memory", or on "has no catalog row" - a channel carrying two
/// meanings is a channel carrying none.
fn data(id: &str, label: &str, fill: &str, outside: bool) -> String {
    let style = if outside { "filled,dashed" } else { "filled" };
    format!("  {id} [shape=box, style=\"{style}\", fillcolor=\"{fill}\", label=\"{label}\"];\n")
}

/// A square holding one value. No segmentation, because there is no history to
/// look back over - a capacity-1 channel holds the current item and nothing else.
fn cell(id: &str, label: &str, fill: &str) -> String {
    format!("  {id} [shape=box, style=filled, fillcolor=\"{fill}\", label=\"{label}\", width=0.45, height=0.45];\n")
}

/// A thing that holds *a history* - segmented, because a reader can look back
/// over it. Never used for something written once.
fn history(id: &str, label: &str, fill: &str) -> String {
    format!("  {id} [shape=record, style=filled, fillcolor=\"{fill}\", label=\"{label}\"];\n")
}

